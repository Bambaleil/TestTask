"""Общая политика экспоненциальной задержки."""


def retry_delay(attempt: int, base: float) -> float:
    """Вычисляет задержку после неудачной попытки.

    Args:
        attempt: Номер завершившейся попытки, начиная с единицы.
        base: Задержка после первой ошибки в секундах.

    Returns:
        Задержка base × 2^(attempt − 1).

    """
    return base * (2.0 ** (attempt - 1))
